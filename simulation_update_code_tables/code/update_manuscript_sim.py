"""Assemble main_revised_v3.tex: Section 3 (discrete-deductible simulation) and the simulation tables of the Appendix
are replaced by the new text (section3_new.tex) and the tables generated by summarize_sim.R (tex_sim/)."""
import re, sys, os

src_tex = sys.argv[1] if len(sys.argv) > 1 else "/home/claude/real/main_revised_v2.tex"
out_tex = sys.argv[2] if len(sys.argv) > 2 else "/home/claude/real/main_revised_v3.tex"
texdir  = sys.argv[3] if len(sys.argv) > 3 else "/home/claude/sim/tex_sim"
sec3    = open("/home/claude/sim/section3_new.tex").read()

def tab(name):
    return open(os.path.join(texdir, name)).read().rstrip() + "\n"

## placeholders @@file.tex@@ -> table files
sec3 = sec3.replace("@@CASE_DISCUSSION@@", open("/home/claude/sim/case_discussion.tex").read())
sec3 = re.sub(r"@@([A-Za-z0-9_]+\.tex)@@", lambda m: tab(m.group(1)), sec3)

main = open(src_tex).read()

## 1. Section 3
i1 = main.index("\\section{Simulation study}")
i2 = main.index("\\section{Empirical Analysis}")
main = main[:i1] + sec3 + "\n" + main[i2:]

## 2. Appendix: simulation tables
a1 = main.index("\\subsection*{Simulation results of deductible, Severity and Frequency}")
a2 = main.index("\\subsection*{Scatterplot of the frequency and joint frequency model selection}")
app = ["\\subsection*{Simulation results of deductible, Severity and Frequency}", "",
       "\\rev{In Tables~\\ref{tab:AppSimDed}--\\ref{tab:AppSimEndCase6}, ``Mean'' and ``RMSE'' are defined in Section~\\ref{sec:simulation}, "
       "``(s.e.)'' is the Monte Carlo standard error of the mean, $\\sqrt{\\text{Var}/R}$, and ``(Bias)'' is the Monte Carlo bias, so that "
       "$\\text{RMSE}^2=R\\times\\text{s.e.}^2+\\text{Bias}^2$ up to rounding, where $R$ is the number of replications. "
       "The dependence parameters are reported on the correlation scale $\\rho=\\sin(\\pi\\tau/2)$ of the Gaussian copula.}", "",
       tab("tab_app_D.tex")]
for cs in [1, 2, 3, 4, 5, 6]:
    if os.path.exists(os.path.join(texdir, f"tab_app_case{cs}_marginal.tex")):
        app += [tab(f"tab_app_case{cs}_marginal.tex"), tab(f"tab_app_case{cs}_joint.tex")]
app += ["\\pagebreak", "\\clearpage"]
main = main[:a1] + "\n".join(app) + "\n" + main[a2:]

## 3. Conclusion: one phrase on the discrete deductible
old = "whereas the proposed joint model \\rev{recovers the true parameters with negligible bias} even with incomplete observations."
new = ("whereas the proposed joint model \\rev{recovers the true parameters with negligible bias} even with incomplete observations"
       "\\rev{, both for the regression coefficients and for the dependence parameters, when the deductible is an ordinal variable as in the LGPIF data}.")
assert old in main; main = main.replace(old, new)


## 4. Remark on the conditional independence assumption (Section 2.2): discrete deductible and Cases 5-6
old = "relaxing it under incomplete data is an interesting direction for future research.}"
new = old + (" \\rev{When the deductible is discrete, the assumption has to be read as conditional independence given the observed "
             "deductible level. If the level were only a coarsening of a continuous latent propensity $U^D$ that also drives the claims, "
             "then $N^*\\perp Y^*\\,|\\,U^D$ would not imply $N^*\\perp Y^*\\,|\\,D$, because the frequency and the severity would remain "
             "dependent through their common position inside the interval of $U^D$ that corresponds to the observed level. The sensitivity "
             "of the joint models to violations of the assumption, including this one, is examined in Cases 5 and 6 of the simulation study "
             "in Section~\\ref{sec:simulation}.}")
assert old in main; main = main.replace(old, new)
old = "%\\authnote{Reviewers 1 and 2 (comment 2) and Reviewer 2 (comment 4) ask for a sensitivity analysis"
i = main.index(old); j = main.index("\n", i); main = main[:i] + main[j + 1:]

open(out_tex, "w").write(main)
print("written", out_tex)
